# Creating Strings
# You can use single quotes ' ' or double quotes " "

name = "Mehedi"
country = 'Bangladesh'

print(name)
print(country)

# string with numbers 
age = "25"
print(age)

# String Concatenation 
first_name = "Naimul"
last_name = "Islam"

full_name = first_name + " " + last_name
print(full_name)

# String Repetition 
word = "Hi "
print(word * 3)