# A for loop is used to repeat a block of code for each item in a sequence or a specific number of times.

# Think of it as:
    # “For each item, do this.”

for number in [1, 2, 3, 4, 5]:
    print(number)

# for loop with a string 
name = "Mehedi"

for letter in name: 
    print(letter)

# for loop with a list 
fruits = ["Apple", "Banana", "Mango"]

for fruit in fruits:
    print(fruit)