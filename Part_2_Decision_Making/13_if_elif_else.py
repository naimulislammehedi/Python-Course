# if...elif...else
# When you need to check multiple conditions, use if...elif...else.

score = 75

if score >= 80:
    print("A")
elif score >= 60:
    print("B")
else:
    print("C")

# Another example 
temperature = 25

if temperature >= 35:
    print("Very hot")
elif temperature >= 30:
    print("Hot")
elif temperature >= 20:
    print("Normal")
else:
    print("Cold")