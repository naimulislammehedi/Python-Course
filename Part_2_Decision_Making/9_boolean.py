# Boolean Values
# In Python, Boolean values represent one of two possible states:
# True
# False

is_student = True 
is_raining = False

print(is_student)
print(is_raining)

# Boolean from Comparisons 
age = 25 
print(age > 18)
print(age < 10)
print(age == 10)
print(age != 10)

# Boolean varaibles: you can store a boolean in a variable 

is_adult = age >= 18
print(is_adult)